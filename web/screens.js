// Склонение слова «период» по числу: 1 период, 2 периода, 5 периодов.
function periodsWord(n) {
  const abs = Math.abs(n);
  const tail100 = abs % 100;
  const tail10 = abs % 10;
  if (tail100 >= 11 && tail100 <= 14) return 'периодов';
  if (tail10 === 1) return 'период';
  if (tail10 >= 2 && tail10 <= 4) return 'периода';
  return 'периодов';
}

// Склонение слова «попытка» по числу: 1 попытка, 2 попытки, 5 попыток.
function attemptsWord(n) {
  const abs = Math.abs(n);
  const tail100 = abs % 100;
  const tail10 = abs % 10;
  if (tail100 >= 11 && tail100 <= 14) return 'попыток';
  if (tail10 === 1) return 'попытка';
  if (tail10 >= 2 && tail10 <= 4) return 'попытки';
  return 'попыток';
}

